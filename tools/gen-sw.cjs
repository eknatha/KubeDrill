// Generates sw.js with a precache list of every shipped asset. Run: node tools/gen-sw.cjs
const fs = require('fs'), path = require('path'), root = path.join(__dirname, '..');
const skip = /^(\.git|node_modules|tests|tools|lab-packs|dist|README\.md|LICENSE|CNAME|sw\.js)/;
const files = []; (function walk(d) { fs.readdirSync(path.join(root, d)).forEach(f => { const rel = path.join(d, f); if (skip.test(rel)) return; if (fs.statSync(path.join(root, rel)).isDirectory()) walk(rel); else files.push(rel.replace(/\\/g, '/')); }); })('');
const crypto = require('crypto'), h = crypto.createHash('sha1'); files.sort().forEach(f => h.update(f).update(fs.readFileSync(path.join(root, f))));
const ver = h.digest('hex').slice(0, 10);
fs.writeFileSync(path.join(root, 'sw.js'), `/* KubeDrill service worker — generated by tools/gen-sw.cjs. Offline-first: everything is precached.
   Updates are applied only when the user clicks "Reload" (message SKIP_WAITING), so a lab/exam is never interrupted. */
const CACHE = 'kubedrill-${ver}';
const ASSETS = ${JSON.stringify(['./'].concat(files), null, 1)};
async function say(msg) { const cs = await self.clients.matchAll({ includeUncontrolled: true }); cs.forEach(c => c.postMessage(msg)); }
self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE); let done = 0; const total = ASSETS.length;
    await say({ type: 'precache', done, total, version: '${ver}' });
    for (const a of ASSETS) { await c.add(new Request(a, { cache: 'reload' })); done++; if (done % 3 === 0 || done === total) await say({ type: 'precache', done, total, version: '${ver}' }); }
  })());
});
self.addEventListener('activate', e => { e.waitUntil((async () => { const ks = await caches.keys(); await Promise.all(ks.filter(k => (k.startsWith('kubedrill-') || k.startsWith('kubelab-')) && k !== CACHE).map(k => caches.delete(k))); await self.clients.claim(); await say({ type: 'ready', version: '${ver}' }); })()); });
self.addEventListener('message', e => { if (e.data === 'SKIP_WAITING') self.skipWaiting(); else if (e.data === 'VERSION') e.source && e.source.postMessage({ type: 'version', version: '${ver}' }); });
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(r => { if (r.ok && new URL(e.request.url).origin === location.origin) { const cp = r.clone(); caches.open(CACHE).then(c => c.put(e.request, cp)); } return r; }).catch(() => caches.match('./'))));
});
`);
console.log('sw.js:', files.length + 1, 'assets, cache kubedrill-' + ver);
